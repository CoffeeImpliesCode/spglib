//! The build half of spglib's runtime route: four modules and two generated
//! files.
//!
//! An SDK that ships the runtime route calls `createModule` in place of
//! `translate.createModule()` and imports what comes back as its `c` module.
//! Nothing here links the native library. That is the point: in this
//! configuration the symbols arrive through the platform loader at run time,
//! and linking the archive as well would make the linker demand them before
//! `load` ever runs.
//!
//!   rt        runtime/loader.zig, the reusable core, supplied by the driver.
//!             Pure Zig; imported by the facade in both configurations, because
//!             `LoadSource` and `LoadError` are this SDK's public types and must
//!             be the same types whichever configuration is built.
//!   library   runtime/library.zig, this SDK's descriptor: the namespaced
//!             synchronization binding and the one load-time check.
//!   dispatch  generated by runtime/generate.zig from the real translation
//!             output: the table, the wrappers, `load`, and the re-exported
//!             translated namespace. It imports `rt`, `library` and the
//!             patched translation as `c_native`.
//!   native    the generator's second file: the same translation with the
//!             `__root` prologue Aro writes replaced by an import of the
//!             dispatch as `c_routed`, so a declaration nested inside a
//!             translated type - `SpglibDataset.spg_free_dataset` - names the
//!             routed wrapper rather than the raw extern. It imports the
//!             dispatch and nothing else.
//!   sync.c    compiled into the dispatch with `-DRT_SYNC_PREFIX=spglib_rt`, so
//!             its symbols cannot collide with another SDK's.
//!
//! ## The one thing a caller must not do
//!
//! Do not link the compiled C archive into a module that imports this dispatch.
//! The facade's `c` import is the dispatch, and nothing else in the graph should
//! reference the library, or the linker resolves the symbols statically and the
//! runtime route silently becomes a linked one.

const std = @import("std");

/// The prefix `runtime/sync.c` is compiled with.
///
/// `runtime/library.zig` declares the same prefix in the symbol names it binds.
/// The two must agree, and a build where they do not fails to link, which is
/// the whole error report: there is no runtime path that could hide it.
///
/// A build that needs a second, independent instance of this SDK in one binary
/// should change this value *and* the prefix in `runtime/library.zig`, and then
/// give the second instance its own copy of both files. Nothing else in the
/// package assumes one instance.
const sync_prefix = "spglib_rt";

/// `extern` declarations that the C library provides and that must therefore
/// stay direct.
///
/// ## Why this list is not empty, and what it actually contains
///
/// The translation unit for the public API is an aggregate that includes
/// exactly one C library header: `include/spglib.h:51` includes `<stddef.h>`
/// and nothing else, and the generated `version.h` this build configures from
/// `src/version.h.in` declares six integer macros. So the set of libc
/// declarations reachable from this translation is whatever `<stddef.h>`
/// reaches, and `<stddef.h>` is the only door in.
///
/// Most of them reach nothing. The Aro compiler's own `stddef.h`
/// (`lib/compiler/aro/include/stddef.h`) declares `ptrdiff_t`, `size_t`,
/// `wchar_t`, `max_align_t`, `NULL`, `offsetof` and `nullptr_t`: no function at
/// all, which is why the recorded translation of this header on a
/// `x86_64-linux-gnu` target contains no libc `extern` at all. The musl,
/// Darwin and BSD `stddef.h` files reach only typedefs for the same reason.
///
/// mingw-w64's `stddef.h` is the exception, and it is a real one: it declares
/// five CRT functions before the ISO C part of the file even starts. Read from
/// `lib/libc/include/any-windows-any/stddef.h`, they are `_errno`
/// (`:14`), `_set_errno` (`:16`), `_get_errno` (`:17`), `__threadid` (`:20`)
/// and `__threadhandle` (`:22`), the first block under `#ifndef
/// _CRT_ERRNO_DEFINED` and the last two unconditional. `stddef.h:7` reaches
/// them through `<crtdefs.h>` -> `<corecrt.h>` -> `<_mingw.h>`, and nothing
/// else in this build's include path defines `_CRT_ERRNO_DEFINED` first.
///
/// Three more come from the same closure, all of them unconditional: `_mingw.h`
/// declares `__debugbreak` (`:576`), `__fastfail` (`:597`) and `__prefetch`
/// (`:622`) under `#ifdef __MINGW_INTRIN_INLINE`, which `_mingw.h:89-90`
/// defines whenever `__GNUC__` is defined, and `_mingw.h:665` declares
/// `__mingw_get_crt_info` outside every conditional. `_mingw_secapi.h:341`
/// declares `__chk_fail` the same way.
///
/// `errno` and `_threadid` are deliberately absent: both are macros at
/// `stddef.h:15` and `:21`, and a macro is not a symbol for the platform
/// loader to find.
///
/// The union is listed rather than any one libc's slice because this build file
/// is target-independent. A name a given target's `<stddef.h>` does not declare
/// matches nothing, which is harmless; a name left out that one does declare
/// would be demanded from the provider at load time and refused, which is not.
const libc_noise =
    \\__chk_fail,__debugbreak,__fastfail,__get_errno,__mingw_get_crt_info,
    \\__prefetch,__threadhandle,__threadid,_errno,_get_errno,_set_errno
;

/// `extern` declarations the provider may legitimately not export.
///
/// Two names, and neither is a guess: `include/spglib.h:544-546` declares
/// `spg_get_grid_points_by_rotations` and `include/spglib.h:551-554` declares
/// `spg_get_BZ_grid_points_by_rotations`. Neither has a definition anywhere in
/// this tree. `src/spglib.c` defines the `size_t` variants of both,
/// `spg_get_dense_grid_points_by_rotations` at `:945` and
/// `spg_get_dense_BZ_grid_points_by_rotations` at `:955`, and defines nothing
/// for the `int`-indexed pair; `rg`-equivalent search over every file in `src/`
/// and `include/` finds the two names in the header and nowhere else.
///
/// A linked build does not notice, because nothing in this package calls either
/// entry point and an `extern` declaration nobody references costs the linker
/// nothing. A loaded build sees the other half of that sentence. `--optional`
/// routes a name to a nullable table field (`generate.zig:237-239`, `:1092`,
/// `:1112`): the field is declared `?<type>`, starts null, and stays null when
/// the provider does not export the symbol. The generated wrapper then ends
/// `table.<name> orelse requireAvailable("<name>", "<name>")`
/// (`generate.zig:1005-1009`), and `requireAvailable` is a
/// `std.debug.panic` that names the library, the symbol the provider lacks and
/// the fact that this provider is not the one the build describes
/// (`generate.zig:975-985`).
///
/// So the failure mode these two names ask for is a named runtime panic at the
/// first call, not a link error and not a failed load: they are listed in the
/// generated `optional_symbols` rather than `symbols`, so their absence never
/// fails a load (`generate.zig:1138-1141`), and the gap is a name in this file
/// rather than a surprise at load time.
///
/// A caller that wants those two k-point entry points wants
/// `spg_get_dense_grid_points_by_rotations` and
/// `spg_get_dense_BZ_grid_points_by_rotations`, which do exist, or the two
/// `spg_relocate_BZ_grid_address` forms at `include/spglib.h:582-589`.
const provider_optional =
    \\spg_get_grid_points_by_rotations,spg_get_BZ_grid_points_by_rotations
;

/// `extern` declarations this build does not require from a provider.
///
/// None. Every entry point `include/spglib.h` declares is expected from a
/// provider except the two named above, and a provider that does not export one
/// of them is refused rather than half used. A name here would be routed into a
/// nullable table field instead: its absence would not fail the load, and its
/// wrapper would stop the program by name. Only `libc_noise` above keeps a
/// declaration direct.
const provider_excluded = "";

/// The loader core, for a *linked* build to import.
///
/// A linked build has no dispatch, so the facade needs the core module itself
/// for the two public types `LoadSource` and `LoadError`: they are this SDK's
/// types and they must be the same types a caller names in either
/// configuration. It costs a linked build two declarations and no code, since
/// nothing else in that module is referenced until a configuration actually
/// instantiates the loader.
///
/// A runtime-loading build must *not* import this separately: `createModule`
/// makes the one core instance the dispatch uses, and the dispatch re-exports
/// the two types from it. Two instances would be two sets of types, and a
/// consumer would be naming one while `load` expects the other.
pub fn createCoreModule(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    return b.createModule(.{
        .root_source_file = b.path("runtime/loader.zig"),
        .target = target,
        .optimize = optimize,
        // The Unix backend calls `dlopen`, which is libc. Nothing in this module
        // is compiled into a linked build, so this costs nothing there.
        .link_libc = true,
    });
}

/// The runtime-loaded `c` module for one target.
///
/// `translate` is the translation step for that same target and configuration;
/// its output is read by the generator, so the dispatch describes the header
/// this build actually selected rather than another one.
pub fn createModule(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    const core = createCoreModule(b, target, optimize);

    const library = b.createModule(.{
        .root_source_file = b.path("runtime/library.zig"),
        .target = target,
        .optimize = optimize,
    });
    library.addImport("rt", core);

    return createDispatchModule(b, translate, target, optimize, core, library);
}

/// What one generator run writes: the dispatch, and the translation it reads.
const GeneratedSources = struct {
    native: std.Build.LazyPath,
    dispatch: std.Build.LazyPath,
};

fn createDispatchModule(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    core: *std.Build.Module,
    library: *std.Build.Module,
) *std.Build.Module {
    const sources = generateDispatch(b, translate, target);

    const dispatch = b.createModule(.{
        .root_source_file = sources.dispatch,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    dispatch.addImport("rt", core);
    dispatch.addImport("library", library);

    // The patched translation, under a name that says what it is. Every type
    // and constant in the dispatch is re-exported from here rather than
    // restated, so `c.SpglibDataset` in a facade and `c_native.SpglibDataset` in
    // the dispatch are one nominal type, and `c_routed` is what makes the
    // members nested inside that type the routed wrappers.
    const native = b.createModule(.{
        .root_source_file = sources.native,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    native.addImport("c_routed", dispatch);
    dispatch.addImport("c_native", native);
    dispatch.addCSourceFiles(.{
        .files = &.{"runtime/sync.c"},
        .flags = &.{b.fmt("-DRT_SYNC_PREFIX={s}", .{sync_prefix})},
        .language = .c,
    });
    return dispatch;
}

/// Runs the generator over the translation step's real output.
///
/// The generator is a host program built and run by this build, so the dispatch
/// is produced for the target being built from that target's own translation.
/// Nothing is cached across configurations: a different header configuration
/// produces a different translation step output, which produces a different
/// dispatch.
fn generateDispatch(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
) GeneratedSources {
    const generator = b.addExecutable(.{
        .name = b.fmt("spglib-runtime-generate-{s}", .{
            target.result.zigTriple(b.allocator) catch @panic("unspellable target"),
        }),
        .root_module = b.createModule(.{
            .root_source_file = b.path("runtime/generate.zig"),
            .target = b.graph.host,
            .optimize = .Debug,
        }),
    });

    const run = b.addRunArtifact(generator);
    run.addArg("--library");
    run.addArg("spglib");
    run.addArg("--translate");
    run.addFileArg(translate.getOutput());
    if (libc_noise.len != 0) {
        run.addArg("--noise");
        run.addArg(libc_noise);
    }
    if (provider_optional.len != 0) {
        run.addArg("--optional");
        run.addArg(provider_optional);
    }
    if (provider_excluded.len != 0) {
        run.addArg("--exclude");
        run.addArg(provider_excluded);
    }
    run.addArg("--native-output");
    const native_source = run.addOutputFileArg("native.zig");
    run.addArg("--output");
    const dispatch_source = run.addOutputFileArg("dispatch.zig");
    return .{ .native = native_source, .dispatch = dispatch_source };
}